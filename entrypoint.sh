#!/bin/sh
# TorScale: Tailscale exit node whose traffic leaves through Tor.
set -eu

TS_HOSTNAME="${TS_HOSTNAME:-torscale}"
TS_AUTHKEY="${TS_AUTHKEY:-}"
TS_LOGIN_SERVER="${TS_LOGIN_SERVER:-}"
TS_EXTRA_ARGS="${TS_EXTRA_ARGS:-}"
TS_PORT="${TS_PORT:-41641}"
TS_IF="${TS_DEVICE:-tailscale0}"
TS_STATE_DIR=/var/lib/tailscale
TS_SOCKET=/var/run/tailscale/tailscaled.sock

TOR_TRANS_PORT=9040
TOR_DNS_PORT=53
TORRC=/etc/tor/torrc
TOR_LOG=/var/log/tor/notices.log
TOR_BOOTSTRAP_TIMEOUT="${TOR_BOOTSTRAP_TIMEOUT:-300}"

log() { echo "[torscale] $*"; }

if [ "${1:-}" = healthcheck ]; then
    grep -q 'Bootstrapped 100%' "$TOR_LOG"
    tailscale --socket="$TS_SOCKET" status > /dev/null
    exit 0
fi

# --- torrc -------------------------------------------------------------------

write_torrc() {
    cat > "$TORRC" <<EOF
# Generated by entrypoint.sh, edit through TOR_* env variables instead.
User tor
DataDirectory /var/lib/tor
Log notice stdout
Log notice file $TOR_LOG

# Transparent proxy for traffic coming in from the tailnet
TransPort 0.0.0.0:$TOR_TRANS_PORT IsolateClientAddr IsolateDestAddr
DNSPort 0.0.0.0:$TOR_DNS_PORT
SocksPort 0

# .onion addresses resolve to a virtual range that is routed into TransPort
VirtualAddrNetworkIPv4 10.192.0.0/10
AutomapHostsOnResolve 1
AutomapHostsSuffixes .onion,.exit

# --- user options from TOR_* env ---
EOF

    # TOR_<Option>[_<suffix>]=<value>  ->  "<Option> <value>"
    # The suffix allows repeating an option: TOR_Bridge_1, TOR_Bridge_2, ...
    has_bridges=0
    has_usebridges=0
    for name in $(env | sed -n 's/^\(TOR_[A-Za-z0-9_]*\)=.*/\1/p' | sort -u); do
        [ "$name" = TOR_BOOTSTRAP_TIMEOUT ] && continue
        opt="${name#TOR_}"
        opt="${opt%%_*}"
        [ -n "$opt" ] || continue
        [ "$opt" = Bridge ] && has_bridges=1
        [ "$opt" = UseBridges ] && has_usebridges=1
        eval "value=\${$name}"
        printf '%s %s\n' "$opt" "$value" >> "$TORRC"
    done

    if [ "$has_bridges" = 1 ] && [ "$has_usebridges" = 0 ]; then
        echo "UseBridges 1" >> "$TORRC"
    fi

    # Raw multi-line torrc snippet
    if [ -n "${TORRC_EXTRA:-}" ]; then
        printf '%s\n' "$TORRC_EXTRA" >> "$TORRC"
    fi
}

start_tor() {
    mkdir -p /var/lib/tor /var/log/tor
    chown -R tor:tor /var/lib/tor /var/log/tor
    chmod 700 /var/lib/tor
    : > "$TOR_LOG"

    log "torrc:"
    sed -e 's/^/    /' "$TORRC"
    tor --verify-config -f "$TORRC" > /dev/null

    tor -f "$TORRC" &
    TOR_PID=$!

    log "waiting for Tor to bootstrap (timeout ${TOR_BOOTSTRAP_TIMEOUT}s)"
    waited=0
    until grep -q 'Bootstrapped 100%' "$TOR_LOG"; do
        kill -0 "$TOR_PID" 2>/dev/null || { log "tor exited"; exit 1; }
        if [ "$waited" -ge "$TOR_BOOTSTRAP_TIMEOUT" ]; then
            log "Tor did not bootstrap in time; check bridges/network"
            exit 1
        fi
        sleep 2
        waited=$((waited + 2))
    done
    log "Tor is ready"
}

# --- firewall ----------------------------------------------------------------

# Tailscale's own netfilter management is disabled, so nothing from the tailnet
# is ever forwarded: TCP and DNS are redirected into Tor, the rest is dropped.
setup_firewall() {
    iptables -t nat -N TORSCALE 2>/dev/null || iptables -t nat -F TORSCALE
    iptables -t nat -A TORSCALE -d 100.64.0.0/10 -j RETURN
    iptables -t nat -A TORSCALE -p udp --dport 53 -j REDIRECT --to-ports "$TOR_DNS_PORT"
    iptables -t nat -A TORSCALE -p tcp --dport 53 -j REDIRECT --to-ports "$TOR_DNS_PORT"
    iptables -t nat -A TORSCALE -p tcp -j REDIRECT --to-ports "$TOR_TRANS_PORT"
    iptables -t nat -C PREROUTING -i "$TS_IF" -j TORSCALE 2>/dev/null \
        || iptables -t nat -A PREROUTING -i "$TS_IF" -j TORSCALE

    iptables -P FORWARD DROP
    iptables -C FORWARD -i "$TS_IF" -j DROP 2>/dev/null \
        || iptables -I FORWARD -i "$TS_IF" -j DROP

    # Tor's TransPort here is IPv4 only. Reject IPv6 quickly so clients fall back.
    if ip6tables -P FORWARD DROP 2>/dev/null; then
        ip6tables -C FORWARD -i "$TS_IF" -j REJECT 2>/dev/null \
            || ip6tables -I FORWARD -i "$TS_IF" -j REJECT
    else
        log "ip6tables unavailable, IPv6 is not forwarded anyway"
    fi
}

# --- tailscale ---------------------------------------------------------------

start_tailscale() {
    mkdir -p "$TS_STATE_DIR" "$(dirname "$TS_SOCKET")"

    tailscaled --state="$TS_STATE_DIR/tailscaled.state" \
               --socket="$TS_SOCKET" \
               --tun="$TS_IF" \
               --port="$TS_PORT" &
    TS_PID=$!

    i=0
    while [ ! -S "$TS_SOCKET" ] && [ "$i" -lt 30 ]; do
        sleep 1
        i=$((i + 1))
    done

    set -- --reset \
        --hostname="$TS_HOSTNAME" \
        --advertise-exit-node \
        --netfilter-mode=off \
        --accept-dns=false \
        --accept-routes=false
    [ -n "$TS_AUTHKEY" ] && set -- "$@" --auth-key="$TS_AUTHKEY"
    [ -n "$TS_LOGIN_SERVER" ] && set -- "$@" --login-server="$TS_LOGIN_SERVER"

    # shellcheck disable=SC2086
    tailscale --socket="$TS_SOCKET" up "$@" $TS_EXTRA_ARGS
    log "tailscale is up: $(tailscale --socket="$TS_SOCKET" ip -4 2>/dev/null || true)"
}

# --- main --------------------------------------------------------------------

# Every DNS lookup in the container (including tailscaled answering exit-node
# DNS queries from clients) goes through Tor.
echo "nameserver 127.0.0.1" > /etc/resolv.conf

write_torrc
setup_firewall
start_tor
start_tailscale

trap 'kill "$TOR_PID" "$TS_PID" 2>/dev/null; exit 0' TERM INT
while kill -0 "$TOR_PID" 2>/dev/null && kill -0 "$TS_PID" 2>/dev/null; do
    sleep 5 &
    wait $! || true
done
log "a child process exited, stopping"
kill "$TOR_PID" "$TS_PID" 2>/dev/null || true
exit 1
